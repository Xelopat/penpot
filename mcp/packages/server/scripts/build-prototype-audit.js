import { build } from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const result = await build({
    entryPoints: [fileURLToPath(new URL("../src/PrototypeAudit.ts", import.meta.url))],
    bundle: true,
    platform: "browser",
    target: "es2022",
    format: "iife",
    globalName: "PenpotPrototypeAudit",
    minify: true,
    write: false,
});
const target = new URL("../src/generated/PrototypeAuditBundle.ts", import.meta.url);
mkdirSync(new URL(".", target), { recursive: true });
writeFileSync(
    target,
    `// Generated by build-prototype-audit.js.\nexport const prototypeAuditBundle = ${JSON.stringify(result.outputFiles[0].text)};\n`
);
